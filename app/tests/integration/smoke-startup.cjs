const {app,BrowserWindow,ipcMain,safeStorage}=require('electron');
const path=require('path'),fs=require('fs'),assert=require('node:assert/strict');
const {io:connect}=require('socket.io-client');
const {createSignalingServer}=require('../../../server/server');
app.disableHardwareAcceleration();app.commandLine.appendSwitch('use-fake-device-for-media-stream');app.commandLine.appendSwitch('use-fake-ui-for-media-stream');
const root=path.resolve(__dirname,"../.."),data=path.join(root,'.runtime-probe','startup-'+process.pid);
app.setPath('userData',data);app.on('window-all-closed',()=>{});
const vault=require('../../main/saved-passwords.cjs').createSavedPasswords(path.join(data,'passwords.json'),safeStorage);
let login=false,starts=0;
ipcMain.handle('get-hardware-acceleration',()=>false);
ipcMain.handle('get-login-startup',()=>login);ipcMain.handle('set-login-startup',(_e,value)=>(login=value));
ipcMain.handle('get-saved-server-password',(_e,url,id)=>vault.get(url,id));ipcMain.handle('save-server-password',(_e,url,id,password)=>vault.set(url,id,password));
ipcMain.handle('start-easytier',()=>{starts++;return '10.144.19.2';});ipcMain.handle('leave-runtime',()=>{});ipcMain.handle('stop-sharing',()=>{});
app.whenReady().then(async()=>{
 const {server,io}=createSignalingServer({initialPeers:'test.example:11010'});let win,owner;
 const request=(event,payload)=>new Promise(resolve=>owner.emit(event,payload,resolve));
 const run=code=>win.webContents.executeJavaScript(code,true);
 const wait=async condition=>{for(let i=0;i<150;i++){if(await run(condition))return;await new Promise(resolve=>setTimeout(resolve,50));}throw Error('Startup timeout: '+condition);};
 const reload=async()=>{const ready=new Promise(resolve=>win.webContents.once('did-finish-load',resolve));win.reload();await ready;};
 try {
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));const url='http://127.0.0.1:'+server.address().port;
  owner=connect(url);await new Promise(resolve=>owner.once('connect',resolve));
  const joined=await request('join-server',{userName:'Owner',virtualIp:'10.144.19.1',identity:'a'.repeat(64),easytierPeers:['tcp://test.example:11010']});
  assert.equal(joined.ok,true,joined.error);
  assert.equal((await request('set-server-password',{enabled:true,password:'first-secret'})).ok,true);
  win=new BrowserWindow({show:false,webPreferences:{preload:path.join(root,'preload.js'),backgroundThrottling:false}});
  await win.loadFile(path.join(root,'renderer/index.html'));
  await run(`document.querySelector('#serverUrl').value='${url}';document.querySelector('#userName').value='Guest';document.querySelector('#btnConnect').click()`);
  await wait(`!!document.querySelector('#serverPasswordInput')`);
  assert.equal(vault.get(url,joined.serverId),'','password is not saved before success');
  await run(`document.querySelector('#serverPasswordInput').value='first-secret';document.querySelector('.password-modal form').requestSubmit()`);
  await wait(`document.querySelector('#room').classList.contains('active')`);
  await wait(`localStorage.getItem('lastConnectedServer')!==null`);
  assert.equal(vault.get(url,joined.serverId),'first-secret');
  assert.ok(!fs.readFileSync(path.join(data,'passwords.json'),'utf8').includes('first-secret'));
  await reload();await wait(`document.querySelector('#room').classList.contains('active')`);
  assert.equal(await run(`!!document.querySelector('#serverPasswordInput')`),false,'auto connect uses encrypted saved password');
  assert.equal((await request('set-server-password',{enabled:true,password:'second-secret'})).ok,true);
  await reload();await wait(`!!document.querySelector('#serverPasswordInput')`);
  assert.equal(vault.get(url,joined.serverId),'','stale password is removed');
  await run(`document.querySelector('#serverPasswordInput').value='second-secret';document.querySelector('.password-modal form').requestSubmit()`);
  await wait(`document.querySelector('#room').classList.contains('active')`);
  assert.equal(await run(`!!document.querySelector('#btnSystemServerSettings')`),false,'system settings has no server settings entry');
  await run(`document.querySelector('#btnServerSettings').click()`);
  assert.equal(await run(`!document.querySelector('#serverSettingsDialog').classList.contains('hidden') && document.querySelector('#serverNameForm').classList.contains('hidden')`),true,'ordinary member sees local settings without owner controls');
  await run(`document.querySelector('#autoJoinChannelCheckbox').click();document.querySelector('#btnCloseServerSettings').click();document.querySelector('#btnLeave').click()`);
  await wait(`document.querySelector('#lobby').classList.contains('active') && !document.querySelector('#btnConnect').disabled`);
  await run(`document.querySelector('#btnConnect').click()`);
  await wait(`document.querySelector('#room').classList.contains('active') && document.querySelector('#channelNameDisplay').textContent==='未加入频道'`);
  await run(`document.querySelector('#btnServerSettings').click();document.querySelector('#autoJoinChannelCheckbox').click();document.querySelector('#btnCloseServerSettings').click()`);
  const music=(await request('create-channel',{name:'Remember music'})).channel;
  await run(`(async()=>{const {switchChannel}=await import('./room.js');await switchChannel('${music.id}');})()`);
  await wait(`!!document.querySelector('.user-card #btnLeaveChannel')`);
  assert.equal(await run(`document.querySelector('.user-card #btnLeaveChannel').title`),'退出');
  await reload();await wait(`document.querySelector('#channelNameDisplay').textContent==='Remember music'`);
  await run(`document.querySelector('.user-card #btnLeaveChannel').click()`);
  await wait(`document.querySelector('#channelNameDisplay').textContent==='未加入频道'`);
  await reload();await wait(`document.querySelector('#room').classList.contains('active') && document.querySelector('#channelNameDisplay').textContent==='主频道'`);
  await run(`document.querySelector('#btnRoomSettings').click()`);
  await wait(`!document.querySelector('#loginStartupCheckbox').disabled`);
  await run(`document.querySelector('#loginStartupCheckbox').click()`);await wait(`!document.querySelector('#loginStartupCheckbox').disabled`);assert.equal(login,true);
  await run(`document.querySelector('#autoConnectCheckbox').click()`);
  const before=starts;await reload();await new Promise(resolve=>setTimeout(resolve,700));
  assert.equal(starts,before,'disabled auto connect does not start networking');assert.equal(await run(`document.querySelector('#lobby').classList.contains('active')`),true);
  console.log('STARTUP_OK',{savedEncrypted:true,autoConnect:true,passwordChange:true,disable:true,loginToggle:true});
 }catch(error){console.error(error.stack);process.exitCode=1;}
 finally{win?.destroy();owner?.disconnect();await new Promise(resolve=>io.close(resolve));app.exit(process.exitCode||0);}
});
